public class Day20 {
    public static void main(String[] args) {
        int a = 10;
        double b = 3.14;
        boolean c = true;
        char d = 'A';
        long e = 123456789L;

        String s1 = String.valueOf(a); // "10"
        String s2 = String.valueOf(b); // "3.14"
        String s3 = String.valueOf(c); // "true"
        String s4 = String.valueOf(d); // "A"
        String s5 = String.valueOf(e); // "123456789"

        System.out.println(s1);
        System.out.println(s2);
        System.out.println(s3);
        System.out.println(s4);
        System.out.println(s5);
    }
}
